#!/usr/bin/env node
/**
 * SessionStart Hook - Auto-provisions docs/MEMORY.md for project context persistence
 *
 * Fires: On startup only (not resume/clear/compact — file already exists after first run)
 * Purpose: Generate project memory bank from detected info so Claude spends fewer tokens
 *          re-discovering project basics on each session start.
 *
 * Behavior:
 *   - If docs/MEMORY.md exists → inject as additionalContext, skip generation
 *   - If docs/MEMORY.md missing → generate from package.json + git + project detection, then inject
 *   - If docs/ dir doesn't exist → skip silently (non-CK project)
 *
 * Exit Codes:
 *   0 - Always (non-blocking)
 */

const fs = require('fs');
const path = require('path');

const MEMORY_PATH = path.resolve('docs', 'MEMORY.md');
const DOCS_DIR = path.resolve('docs');
const MAX_LINES = 200;

/**
 * Resolve the user-level auto memory path
 * Claude Code stores per-project memory at ~/.claude/projects/{cwd-encoded}/memory/MEMORY.md
 * The CWD is encoded by replacing path separators with dashes
 */
function getUserMemoryPath() {
  const home = process.env.HOME || process.env.USERPROFILE || '';
  if (!home) return null;
  const { encodeCwdPath } = require('./lib/ck-paths.cjs');
  return path.join(home, '.claude', 'projects', encodeCwdPath(), 'memory', 'MEMORY.md');
}

/**
 * Detect project info from filesystem (lightweight, no shell calls)
 * Mirrors session-init.cjs detection but returns structured data
 */
function detectProject() {
  const info = {
    name: null,
    type: 'single-repo',
    pm: null,
    framework: null,
    nodeEngine: null,
    testScript: null,
    commitStyle: null,
    hasCK: fs.existsSync('.claude'),
    srcDirs: [],
    testDirs: []
  };

  // Package.json detection
  try {
    if (fs.existsSync('package.json')) {
      const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
      info.name = pkg.name || null;

      // Project type
      if (pkg.workspaces) info.type = 'monorepo';
      else if (pkg.main || pkg.exports) info.type = 'library';
      else info.type = 'app';

      // Engine
      info.nodeEngine = pkg.engines?.node || null;

      // Test script
      info.testScript = pkg.scripts?.test || null;

      // Framework
      const deps = { ...pkg.dependencies, ...pkg.devDependencies };
      const frameworks = [
        ['next', 'Next.js'], ['nuxt', 'Nuxt'], ['astro', 'Astro'],
        ['@remix-run/node', 'Remix'], ['svelte', 'SvelteKit'],
        ['vue', 'Vue'], ['react', 'React'], ['express', 'Express'],
        ['fastify', 'Fastify'], ['hono', 'Hono'], ['elysia', 'Elysia']
      ];
      for (const [dep, name] of frameworks) {
        if (deps[dep]) { info.framework = name; break; }
      }

      // Commit style
      if (deps['@commitlint/cli'] || deps['commitlint']) info.commitStyle = 'conventional';
    }
  } catch { /* skip */ }

  // Package manager
  if (fs.existsSync('bun.lockb') || fs.existsSync('bun.lock')) info.pm = 'bun';
  else if (fs.existsSync('pnpm-lock.yaml')) info.pm = 'pnpm';
  else if (fs.existsSync('yarn.lock')) info.pm = 'yarn';
  else if (fs.existsSync('package-lock.json')) info.pm = 'npm';

  // Monorepo indicators
  if (fs.existsSync('pnpm-workspace.yaml') || fs.existsSync('lerna.json')) info.type = 'monorepo';

  // Source directories
  for (const dir of ['src', 'lib', 'app', 'pages', 'components']) {
    if (fs.existsSync(dir)) info.srcDirs.push(dir + '/');
  }

  // Test directories
  for (const dir of ['tests', 'test', '__tests__', 'spec']) {
    if (fs.existsSync(dir)) info.testDirs.push(dir + '/');
  }

  return info;
}

/**
 * Generate MEMORY.md content from detected project info
 */
function generateMemory(info) {
  const lines = [
    '# Project Memory Bank',
    '',
    '> Auto-generated by ClaudeKit on first session. Edit freely — this file is never overwritten.',
    '> Claude reads this on every session start to reduce token waste.',
    '',
    '## Project',
    '',
    `- **Name:** ${info.name || path.basename(process.cwd())}`,
    `- **Type:** ${info.type}${info.pm ? ` (${info.pm})` : ''}`,
  ];

  if (info.framework) lines.push(`- **Framework:** ${info.framework}`);
  if (info.nodeEngine) lines.push(`- **Node:** ${info.nodeEngine}`);
  if (info.commitStyle) lines.push(`- **Commits:** ${info.commitStyle}`);

  lines.push('', '## Key Paths', '');

  if (info.srcDirs.length > 0) lines.push(`- **Source:** ${info.srcDirs.join(', ')}`);
  if (info.testDirs.length > 0) lines.push(`- **Tests:** ${info.testDirs.join(', ')}`);
  lines.push('- **Docs:** docs/');
  if (info.hasCK) {
    lines.push('- **Hooks:** .claude/hooks/');
    lines.push('- **Commands:** .claude/commands/');
    lines.push('- **Agents:** .claude/agents/');
  }

  if (info.testScript) {
    lines.push('', '## Testing', '');
    lines.push(`- **Run:** \`${info.pm || 'npm'} test\``);
    lines.push(`- **Script:** \`${info.testScript.length > 80 ? info.testScript.slice(0, 77) + '...' : info.testScript}\``);
  }

  lines.push(
    '',
    '## Architecture Decisions',
    '',
    '<!-- Confirmed decisions — append with date, e.g.: "- JWT in httpOnly cookies (260225)" -->',
    '',
    '## Conventions',
    '',
    '<!-- Discovered patterns — e.g.: "- All hooks exit 0 (non-blocking)" -->',
    '',
    '## Known Issues',
    '',
    '<!-- Bugs, tech debt — tag severity: [HIGH], [MED], [LOW] -->',
    '',
    '## Integration Notes',
    '',
    '<!-- API quirks, library gotchas — e.g.: "- Stripe: always use idempotency keys" -->',
    ''
  );

  return lines.join('\n');
}

try {
  // Skip if no docs/ directory (non-CK project or not yet bootstrapped)
  if (!fs.existsSync(DOCS_DIR)) process.exit(0);

  // Generate project memory if missing (one-time only)
  if (!fs.existsSync(MEMORY_PATH)) {
    const info = detectProject();
    const content = generateMemory(info);
    fs.writeFileSync(MEMORY_PATH, content, 'utf8');
  }

  // Collect memory from both sources
  const parts = [];

  // 1. Project-level memory (docs/MEMORY.md) — shared, version-controlled
  const projectMemory = fs.readFileSync(MEMORY_PATH, 'utf8').trim();
  if (projectMemory) parts.push(projectMemory);

  // 2. User-level auto memory (~/.claude/projects/{cwd}/memory/MEMORY.md) — personal
  const userMemoryPath = getUserMemoryPath();
  if (userMemoryPath && fs.existsSync(userMemoryPath)) {
    try {
      const userMemory = fs.readFileSync(userMemoryPath, 'utf8').trim();
      if (userMemory) {
        parts.push('\n---\n## User Memory (personal)\n\n' + userMemory);
      }
    } catch { /* skip unreadable user memory */ }
  }

  // Combine and truncate
  const combined = parts.join('\n');
  const lines = combined.split('\n');
  const truncated = lines.length > MAX_LINES
    ? lines.slice(0, MAX_LINES).join('\n') + '\n\n<!-- Truncated at 200 lines -->'
    : combined;

  if (truncated.length > 0) {
    console.log(JSON.stringify({ additionalContext: truncated }));
  }

  // Write hook status summary for statusline (non-blocking)
  try {
    const ckPaths = require('./lib/ck-paths.cjs');
    ckPaths.ensureDir(ckPaths.CK_TMP_DIR);

    // Count hooks from settings.json
    let hookCount = 0;
    const settingsPath = path.resolve('.claude', 'settings.json');
    if (fs.existsSync(settingsPath)) {
      const settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8'));
      for (const evtHooks of Object.values(settings.hooks || {})) {
        for (const matcher of evtHooks) hookCount += (matcher.hooks || []).length;
      }
    }

    // Count active plans (pending/in_progress)
    let planCount = 0;
    try {
      const planDirs = fs.readdirSync('plans', { withFileTypes: true });
      for (const d of planDirs) {
        if (!d.isDirectory() || ['reports', 'archive', 'templates'].includes(d.name)) continue;
        const pf = path.join('plans', d.name, 'plan.md');
        if (fs.existsSync(pf)) {
          const head = fs.readFileSync(pf, 'utf8').slice(0, 500);
          if (/status:\s*(pending|in_progress)/i.test(head)) planCount++;
        }
      }
    } catch { /* no plans dir */ }

    const status = {
      ts: Math.floor(Date.now() / 1000),
      hooks: hookCount,
      memory: true,
      plans: planCount,
      project: path.basename(process.cwd())
    };
    const tmp = ckPaths.HOOK_STATUS_PATH + '.tmp';
    fs.writeFileSync(tmp, JSON.stringify(status), 'utf8');
    fs.renameSync(tmp, ckPaths.HOOK_STATUS_PATH);
  } catch { /* non-blocking */ }
} catch {
  // Non-blocking — exit silently on any error
}
